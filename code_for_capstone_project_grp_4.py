"""## **Statistical Analysis using SciPy**

### **Shapiro-Wilk Test (Normality):**
The Shapiro-Wilk test checks whether our resistance data significantly deviates from a normal distribution.
"""

from scipy.stats import shapiro

for bacteria, group in df.groupby("Bacteria"):
    statistic, p_value = shapiro(group["Resistance_pct"])

    print(f"\n{bacteria}")
    print("Test statistic:", round(statistic, 4))
    print("P-value:", round(p_value, 4))

    if p_value > 0.05:
        print("Conclusion: Data is approximately normally distributed.")
    else:
        print("Conclusion: Data significantly deviates from normality.")

"""**Conclusion:** The Shapiro-Wilk test indicated that resistance values for all three bacterial species deviate significantly from a normal distribution (p < 0.05). Therefore, a non-parametric test such as the Kruskal-Wallis test is also appropriate when comparing the species.

### **One-Way ANOVA and Kruskal-Wallis Test:**
Check whether the average resistance differs significantly between the three bacterial species.
"""

from scipy.stats import f_oneway, kruskal

ecoli = df[df["Bacteria"] == "Escherichia coli"]["Resistance_pct"]
klebsiella = df[df["Bacteria"] == "Klebsiella pneumoniae"]["Resistance_pct"]
staph = df[df["Bacteria"] == "Staphylococcus aureus"]["Resistance_pct"]

# One-Way ANOVA
f_stat, anova_p = f_oneway(ecoli, klebsiella, staph)

# Kruskal-Wallis Test
h_stat, kruskal_p = kruskal(ecoli, klebsiella, staph)

print("ONE-WAY ANOVA")
print("F-statistic:", round(f_stat, 4))
print("P-value:", anova_p)

print("\nKRUSKAL-WALLIS TEST")
print("H-statistic:", round(h_stat, 4))
print("P-value:", kruskal_p)

"""**Conclusion:** One-way ANOVA showed a statistically significant difference in mean antimicrobial resistance among the three bacterial species (F = 114.6182, p < 0.05).

The Kruskal-Wallis test also indicated a significant difference (H = 117.4927, p < 0.05). These findings suggest that antimicrobial resistance varies significantly across bacterial species. However, further pairwise testing would be required to identify exactly which species differ.

###**Pearson and Spearman Correlation Tests:**

Add p-values to determine whether the observed correlations are statistically significant.
"""

from scipy.stats import pearsonr, spearmanr

x = df["Total_J01_DDD_per_1000"]
y = df["Resistance_pct"]

